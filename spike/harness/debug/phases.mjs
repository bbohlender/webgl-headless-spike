// Splits the first frame into: program compile, texture upload, first draw, second draw.
import { readFile } from "node:fs/promises";
import { createCanvas, installGlobals, readCanvas } from "../env.js";
installGlobals();
const THREE = await import("three");
const { buildScene, rendererOptions } = await import("../scenes.js");
const name = process.argv[2] ?? "tokyo";
const [w, h] = [1280, 720];
const opts = rendererOptions(name);
const canvas = createCanvas(w, h, { libDir: process.env.ANGLE_DIR, blobCacheDir: process.env.ANGLE_BLOB_CACHE_DIR, alpha: opts.alpha });
const gl = canvas.getContext("webgl2");
const renderer = new THREE.WebGLRenderer({ canvas, context: gl, antialias: false, alpha: opts.alpha, preserveDrawingBuffer: true });
renderer.setSize(w, h, false);
renderer.shadowMap.enabled = opts.shadows;
let t = performance.now();
const lap = (label) => { gl.finish(); const n = performance.now(); console.log(label.padEnd(14), Math.round(n - t), "ms"); t = n; };
const { scene, camera } = await buildScene(name, renderer, (p) => readFile(new URL("../" + p, import.meta.url)).then((b) => b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)), w / h);
lap("scene+pmrem");
renderer.compile(scene, camera);
lap("compile");
const textures = new Set();
scene.traverse((o) => { for (const m of [o.material].flat()) if (m) for (const v of Object.values(m)) if (v?.isTexture) textures.add(v); });
for (const tex of textures) renderer.initTexture(tex);
lap(`upload(${textures.size})`);
renderer.render(scene, camera); readCanvas(gl);
lap("first draw");
renderer.render(scene, camera); readCanvas(gl);
lap("second draw");
