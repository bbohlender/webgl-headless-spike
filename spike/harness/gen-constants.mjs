// Generates constants.js: every GL_* enum from the GLES 2/3 headers (without the GL_ prefix),
// plus the WebGL-only and ANGLE enums the WebGL layer uses.
import { readFileSync, writeFileSync } from "node:fs";

const C = {};
for (const header of ["addon/include/GLES2/gl2.h", "addon/include/GLES3/gl3.h"]) {
  for (const m of readFileSync(header, "utf8").matchAll(/^#define GL_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)u?\s*$/gm)) {
    if (/^(ES_VERSION|GLES|VERSION_ES)/.test(m[1])) continue;
    C[m[1]] ??= Number(m[2]);
  }
}
Object.assign(C, {
  UNPACK_FLIP_Y_WEBGL: 0x9240, UNPACK_PREMULTIPLY_ALPHA_WEBGL: 0x9241, CONTEXT_LOST_WEBGL: 0x9242,
  UNPACK_COLORSPACE_CONVERSION_WEBGL: 0x9243, BROWSER_DEFAULT_WEBGL: 0x9244, UNMASKED_VENDOR_WEBGL: 0x9245,
  UNMASKED_RENDERER_WEBGL: 0x9246, MAX_CLIENT_WAIT_TIMEOUT_WEBGL: 0x9247,
  REQUESTABLE_EXTENSIONS_ANGLE: 0x93a8, COMPLETION_STATUS_KHR: 0x91b1, MAX_TEXTURE_MAX_ANISOTROPY_EXT: 0x84ff,
});
writeFileSync("constants.js", `// Generated by gen-constants.mjs. Do not edit.\nexport const C = Object.freeze(${JSON.stringify(C, null, 1)});\n`);
console.log(Object.keys(C).length, "constants");
