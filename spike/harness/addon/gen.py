"""Generates gl_gen.c: one Node-API wrapper per OpenGL ES 3.0 entry point in include/GLES3/gl3.h.

Argument mapping (JS -> C):
  GLenum/GLuint/GLbitfield/GLint/GLsizei/GLboolean   number (booleans accepted)
  GLfloat                                             number
  GLintptr/GLsizeiptr                                 number
  GLint64/GLuint64                                    number or BigInt
  GLsync                                              BigInt (opaque pointer)
  const GLchar *                                      string
  any other pointer                                   TypedArray / ArrayBuffer / DataView (data pointer),
                                                      number (byte offset into a bound buffer), or null
Return values: GLboolean -> boolean, const GLubyte * -> string, GLsync -> BigInt, other scalars -> number.
Entry points taking string arrays or returning raw pointers are written by hand in gl.c.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
HANDWRITTEN = {"glShaderSource", "glTransformFeedbackVaryings", "glGetUniformIndices",
               "glGetVertexAttribPointerv", "glGetBufferPointerv", "glMapBufferRange"}

UNSIGNED = {"GLenum", "GLuint", "GLbitfield"}
SIGNED = {"GLint", "GLsizei"}
FLOAT = {"GLfloat"}
PTRSIZE = {"GLintptr", "GLsizeiptr"}
WIDE = {"GLint64", "GLuint64"}


def parse(header: Path):
    proto = re.compile(r"^GL_APICALL (.+?)\s*GL_APIENTRY (gl\w+) \((.*)\);$")
    for line in header.read_text().splitlines():
        m = proto.match(line)
        if not m:
            continue
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        args = []
        if params != "void":
            for p in params.split(","):
                p = p.strip()
                pm = re.match(r"^(.*?)(\w+)$", p)
                args.append((pm.group(1).strip(), pm.group(2)))
        yield ret, name, args


def convert_arg(ctype: str, cname: str, i: int) -> str:
    if "*" in ctype:
        if ctype.replace(" ", "") == "constGLchar*":
            return f"  char *{cname} = arg_string(env, argv[{i}]);\n"
        return f"  {ctype} {cname} = ({ctype})arg_pointer(env, argv[{i}]);\n"
    if ctype in UNSIGNED:
        return f"  {ctype} {cname} = ({ctype})arg_uint(env, argv[{i}]);\n"
    if ctype in SIGNED:
        return f"  {ctype} {cname} = ({ctype})arg_int(env, argv[{i}]);\n"
    if ctype == "GLboolean":
        return f"  GLboolean {cname} = (GLboolean)arg_bool(env, argv[{i}]);\n"
    if ctype in FLOAT:
        return f"  GLfloat {cname} = (GLfloat)arg_double(env, argv[{i}]);\n"
    if ctype in PTRSIZE:
        return f"  {ctype} {cname} = ({ctype})arg_double(env, argv[{i}]);\n"
    if ctype in WIDE:
        return f"  {ctype} {cname} = ({ctype})arg_wide(env, argv[{i}]);\n"
    if ctype == "GLsync":
        return f"  GLsync {cname} = (GLsync)(uintptr_t)arg_wide(env, argv[{i}]);\n"
    raise ValueError(f"unhandled type {ctype}")


def convert_ret(ret: str) -> str:
    if ret == "void":
        return "  return NULL;\n"
    if ret == "GLboolean":
        return "  return ret_bool(env, r);\n"
    if ret == "const GLubyte *":
        return "  return ret_string(env, (const char *)r);\n"
    if ret == "GLsync":
        return "  return ret_bigint(env, (uint64_t)(uintptr_t)r);\n"
    if ret in UNSIGNED:
        return "  return ret_uint(env, r);\n"
    if ret in SIGNED:
        return "  return ret_int(env, r);\n"
    raise ValueError(f"unhandled return {ret}")


def main():
    funcs = [f for f in parse(HERE / "include/GLES3/gl3.h") if f[1] not in HANDWRITTEN]
    out = ['// Generated by gen.py from include/GLES3/gl3.h. Do not edit.\n#include "gl.h"\n\n']
    for ret, name, args in funcs:
        params = ", ".join(f"{t} {n}" for t, n in args) or "void"
        out.append(f"typedef {ret} (GL_APIENTRY *PFN_{name})({params});\nstatic PFN_{name} p_{name};\n")
    out.append("\n")
    for ret, name, args in funcs:
        body = [f"static napi_value w_{name}(napi_env env, napi_callback_info info) {{\n"]
        body.append(f"  size_t argc = {max(len(args), 1)};\n  napi_value argv[{max(len(args), 1)}];\n")
        body.append(f"  napi_get_cb_info(env, info, &argc, argv, NULL, NULL);\n")
        body.append(f"  if (argc < {len(args)}) return throw_arity(env, \"{name}\", {len(args)});\n")
        for i, (t, n) in enumerate(args):
            body.append(convert_arg(t, n, i))
        call = f"p_{name}({', '.join(n for _, n in args)})"
        body.append(f"  {'' if ret == 'void' else ret + ' r = '}{call};\n")
        for t, n in args:
            if t.replace(" ", "") == "constGLchar*":
                body.append(f"  free({n});\n")
        body.append(convert_ret(ret))
        body.append("}\n\n")
        out.append("".join(body))
    out.append("void gl_gen_load(void *(*load)(const char *)) {\n")
    for _, name, _ in funcs:
        out.append(f"  p_{name} = (PFN_{name})load(\"{name}\");\n")
    out.append("}\n\nvoid gl_gen_export(napi_env env, napi_value exports) {\n")
    for _, name, _ in funcs:
        out.append(f"  export_fn(env, exports, \"{name}\", w_{name});\n")
    out.append("}\n")
    (HERE / "gl_gen.c").write_text("".join(out))
    print(f"generated {len(funcs)} wrappers", file=sys.stderr)


main()
